enum DemoContent {

    /// 当前进程是否请求注入演示数据
    static var isRequested: Bool {
        ProcessInfo.processInfo.arguments.contains("-demoContent")
    }

    /// 仅在书库为空时注入，避免重复启动产生重复文章
    static func seedIfNeeded(context: ModelContext) {
        guard isRequested else { return }
        let count = (try? context.fetchCount(FetchDescriptor<Article>())) ?? 0
        guard count == 0 else { return }

        for demo in articles {
            let article = Article(
                title: demo.title,
                sourceURL: demo.url,
                sourceType: demo.sourceType,
                paragraphs: demo.paragraphs,
                createdAt: demo.createdAt
            )
            context.insert(article)
            for (level, text) in demo.summaries {
                context.insert(SummaryLevel(level: level, text: text, article: article))
            }
        }
        try? context.save()
    }

